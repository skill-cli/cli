struct StateBoundaryTests {
  @Test(arguments: [InstallScope.project, .user])
  func lifecyclePreservesInstructions(_ scope: InstallScope) throws {
    let fixture = try CLIFixture()
    try fixture.skill()
    try fixture.commit()
    let scopeArguments = ["--scope", scope.rawValue]
    try fixture.success(["add", fixture.source.path, "demo", "--mode", "copy"] + scopeArguments)
    let store = StateStore(
      scope: scope,
      environment: RuntimeEnvironment(
        projectDirectory: fixture.project, homeDirectory: fixture.home,
        environment: fixture.environment))
    let alias = try #require(try store.loadDeclaration().sources.keys.first)
    try fixture.editManifest(scope: scope.rawValue) { _ in
      [
        .insertComponent(
          .instructions(
            sections: [.section(name: "rules", source: alias)],
            chatGPT: [
              .prompt(
                name: "daily", sections: [.section(name: "rules", source: alias)],
                append: "custom.md")
            ], agents: [.codex]), into: .root, at: .first)
      ]
    }
    let declaration = try store.loadDeclaration()
    var resolved = try store.loadResolved()
    let pin = try #require(resolved.skills["demo"])
    let section = LockedSection(
      name: "rules", source: pin.source, revision: pin.revision,
      path: "instructions/rules.md", hash: try #require(pin.hash))
    let targetRoot = scope == .user ? fixture.home : fixture.project
    let targetKey = scope == .user ? "~/.codex/AGENTS.md" : "AGENTS.md"
    resolved.instructions = LockedInstructions(
      sections: [section],
      chatgpt: ["daily": LockedPrompt(sections: [section], append: "custom.md")],
      targets: [
        targetKey: LockedTarget(
          agents: [.codex], headingOffset: 0, blockHash: section.hash, created: false)
      ])
    try JSONEncoder().encode(resolved).write(to: store.resolvedURL)
    try fixture.success(["watch", "add", fixture.source.path] + scopeArguments)
    var watch = try Data(contentsOf: store.watchURL)
    let targetPaths =
      scope == .user
      ? [".codex/AGENTS.md", ".claude/CLAUDE.md", ".gemini/GEMINI.md", "custom.md"]
      : ["AGENTS.md", "CLAUDE.md", "GEMINI.md", "custom.md"]
    let targetBytes = Data("Owner instructions\r\n<!-- untouched -->\r\n".utf8)
    for path in targetPaths {
      let url = targetRoot.appendingPathComponent(path)
      try FileManager.default.createDirectory(
        at: url.deletingLastPathComponent(), withIntermediateDirectories: true)
      try targetBytes.write(to: url)
    }
    let installed = targetRoot.appendingPathComponent(".agents/skills/demo/SKILL.md")
    try FileManager.default.removeItem(at: installed)
    try fixture.skill(body: "New committed skill")
    try fixture.commit()
    for command in [
      ["list", "--json"], ["install", "--json"], ["update", "--json"], ["update", "--apply"],
      ["add", fixture.source.path, "demo"], ["doctor", "--json"],
      ["watch", "add", fixture.source.path], ["watch", "status", "--json"],
      ["watch", "diff", fixture.source.path, "--json"], ["watch", "seen", fixture.source.path],
      ["watch", "remove", fixture.source.path], ["remove", "demo"],
    ] {
      try fixture.success(command + scopeArguments)
      if command.first == "watch" {
        watch = try Data(contentsOf: store.watchURL)
      } else {
        #expect(try Data(contentsOf: store.watchURL) == watch)
      }
      #expect(try store.loadDeclaration().instructions == declaration.instructions)
      #expect(try store.loadResolved().instructions == resolved.instructions)
      #expect(try store.loadResolved().sources[pin.source] == resolved.sources[pin.source])
      for path in targetPaths {
        #expect(try Data(contentsOf: targetRoot.appendingPathComponent(path)) == targetBytes)
      }
    }
    if scope == .project {
      try fixture.success(["doctor", "--root", fixture.project.path, "--json"])
      #expect(try store.loadResolved().instructions == resolved.instructions)
      for path in targetPaths {
        #expect(try Data(contentsOf: targetRoot.appendingPathComponent(path)) == targetBytes)
      }
    }
  }

  @Test func projectStateFromAgentsKeepsItsBytes() throws {
    let fixture = try CLIFixture()
    try fixture.skill()
    try fixture.commit()
    func hash(_ bytes: Data) -> String {
      "sha256:" + SHA256.hash(data: bytes).map { String(format: "%02x", $0) }.joined()
    }
    let body = "# Guide\n\nKeep it small.\n"
    let own = Data("---\ndescription: Repository guide\n---\n\n\(body)".utf8)
    let agentsFile = Data(
      """
      <!-- Generated by agents from instruction files. Edit those files and run `agents update`. -->

      \(body)
      """.utf8)
    let declaration = Data(
      """
      // agents-tools-version: 1.0
      import AgentsDescription

      // Repository-owned instruction order and comments.
      let agents = Agents(
        components: [
          // Guide belongs to both recipients.
          .instructions(sections: ["guide"], agents: [.claudeCode, .codex]),
        ]
      )

      """.utf8)
    let resolved = Data(
      """
      {
        "instructions": {
          "chatgpt": {},
          "sections": [
            {
              "hash": "\(hash(own))",
              "name": "guide",
              "path": ".agent/instructions/guide.md",
              "source": "."
            }
          ],
          "targets": {
            "AGENTS.md": {
              "agents": ["claude-code", "codex"],
              "blockHash": "\(hash(agentsFile))",
              "created": false,
              "headingOffset": 0
            }
          }
        },
        "skills": {},
        "sources": {},
        "version": 1
      }

      """.utf8)
    let files = [
      ".agent/Agents.swift": declaration, ".agent/agents.resolved": resolved,
      ".agent/instructions/guide.md": own, "AGENTS.md": agentsFile,
    ]
    for (path, bytes) in files {
      let url = fixture.project.appendingPathComponent(path)
      try FileManager.default.createDirectory(
        at: url.deletingLastPathComponent(), withIntermediateDirectories: true)
      try bytes.write(to: url)
    }
    for command in [["list", "--json"], ["doctor", "--json"], ["update", "--json"], ["install"]] {
      try fixture.success(command)
      for (path, bytes) in files {
        #expect(try Data(contentsOf: fixture.project.appendingPathComponent(path)) == bytes)
      }
    }
    let store = StateStore(
      scope: .project,
      environment: RuntimeEnvironment(
        projectDirectory: fixture.project, homeDirectory: fixture.home,
        environment: fixture.environment))
    let instructions = try store.loadDeclaration().instructions
    let lockedInstructions = try store.loadResolved().instructions
    for command in [["add", fixture.source.path, "demo"], ["remove", "demo"]] {
      try fixture.success(command)
      #expect(try store.loadDeclaration().instructions == instructions)
      #expect(try store.loadResolved().instructions == lockedInstructions)
      let text = try String(contentsOf: fixture.state("Agents.swift"), encoding: .utf8)
      #expect(text.contains("// Repository-owned instruction order and comments."))
      #expect(text.contains("// Guide belongs to both recipients."))
      #expect(text.contains(".instructions(sections: [\"guide\"], agents: [.claudeCode, .codex])"))
      for path in [".agent/instructions/guide.md", "AGENTS.md"] {
        #expect(try Data(contentsOf: fixture.project.appendingPathComponent(path)) == files[path])
      }
    }
  }

  @Test(arguments: ["project", "user"])
  func stateUsesAgentsFiles(_ scope: String) throws {
    let fixture = try CLIFixture()
    try fixture.skill()
    try fixture.commit()
    let legacy = ["skills.resolved", "skills-state.json"]
    let bytes = Data("unreadable legacy state\n".utf8)
    for name in legacy {
      let url = fixture.state(name, scope: scope)
      try FileManager.default.createDirectory(
        at: url.deletingLastPathComponent(), withIntermediateDirectories: true)
      try bytes.write(to: url)
    }
    try fixture.success(["add", fixture.source.path, "--scope", scope])
    try fixture.success(["install", "--scope", scope])
    for name in ["Agents.swift", "agents.resolved"] {
      #expect(FileManager.default.fileExists(atPath: fixture.state(name, scope: scope).path))
    }
    for name in legacy {
      #expect(try Data(contentsOf: fixture.state(name, scope: scope)) == bytes)
    }
  }
}
